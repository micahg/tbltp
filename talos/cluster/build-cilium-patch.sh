#!/usr/bin/env bash
# Render Cilium and embed it in a Talos machine-config patch (inlineManifests).
# Output: patches/cilium.yaml (generated - edit cilium/values.yaml instead).
set -euo pipefail
cd "$(dirname "$0")"
VERSION=$(cat cilium/version.txt)
helm template cilium cilium --repo https://helm.cilium.io --version "$VERSION" \
  --namespace kube-system --values cilium/values.yaml > /tmp/cilium-rendered.yaml
{
  echo "# GENERATED by build-cilium-patch.sh (Cilium $VERSION) - do not edit."
  echo "cluster:"
  echo "  inlineManifests:"
  echo "    - name: cilium"
  echo "      contents: |"
  sed 's/^/        /' /tmp/cilium-rendered.yaml
} > patches/cilium.yaml
rm /tmp/cilium-rendered.yaml
echo "wrote patches/cilium.yaml ($(wc -l < patches/cilium.yaml) lines)"
